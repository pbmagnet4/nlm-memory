/**
 * Fit the Clef ingest gate (T644) on answers from clef-gate-collect.ts.
 *
 * Label: the classifier stored at least one decision or live fact for the session.
 * Training uses the tune half (fixed id hash) of the yield and live sets. The skip
 * threshold is the highest one that loses at most 0.5% of tune decisions and 2.5% of
 * tune facts. Everything is reported on holdout halves, plus the audited set, next to
 * the zero-shot baseline (importance below 1.5).
 *
 * Run:   npx tsx scripts/eval/clef-gate-fit.ts
 * Write: npx tsx scripts/eval/clef-gate-fit.ts --write   (regenerates src/core/classifier/gate-model-params.ts)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { GATE_FEATURES, gateFeatures, gateProbability, type GateModel } from "../../src/core/classifier/gate-model.js";
import type { GateRow } from "./clef-gate-collect.js";
import { fitLogReg } from "./lib/logreg.js";
import { auc, splitOf, wilson } from "./lib/clef-stats.js";

const MAX_DECISION_LOSS = 0.005;
const MAX_FACT_LOSS = 0.025;
const BASELINE = 1.5;

const HOME = homedir();
const evalDir = (process.env["NLM_EVAL_DATA_DIR"] ?? join(HOME, ".nlm", "eval")).replace(/^~/, HOME);
const rows = (JSON.parse(readFileSync(join(evalDir, "gate-tune", "answers.json"), "utf8")) as GateRow[]).filter((r) => r.answers);
const worthwhile = new Map((JSON.parse(readFileSync(join(evalDir, "triage", "labels-final.json"), "utf8")) as { id: string; importance: number }[])
  .map((l) => [l.id, l.importance >= 2]));

interface Scored { row: GateRow; x: number[]; y: number; imp: number }
const scored: Scored[] = rows.map((row) => {
  const a = row.answers!;
  const imp = a["importance"];
  return { row, x: gateFeatures(a, row.chars), y: row.decisions + row.facts > 0 ? 1 : 0, imp: imp?.type === "score" ? imp.score : 3 };
});
const train = scored.filter((s) => s.row.set !== "audited" && splitOf(s.row.id) === "tune");
const fit = fitLogReg(train.map((s) => s.x), train.map((s) => s.y), { l2: 0.01, iters: 4000, lr: 0.3 });

const prob = (s: Scored) => gateProbability({ ...fit, threshold: 0 }, s.x);
const cost = (set: Scored[], skip: (s: Scored) => boolean) => {
  const sk = set.filter(skip);
  const sum = (xs: Scored[], k: "decisions" | "facts") => xs.reduce((n, s) => n + s.row[k], 0);
  return { skipped: sk.length, n: set.length, dLost: sum(sk, "decisions"), dAll: sum(set, "decisions"), fLost: sum(sk, "facts"), fAll: sum(set, "facts") };
};

const candidates = [...new Set(train.map(prob))].sort((a, b) => a - b);
let threshold = 0;
for (const t of candidates) {
  const c = cost(train, (s) => prob(s) < t);
  if (c.dLost <= MAX_DECISION_LOSS * c.dAll && c.fLost <= MAX_FACT_LOSS * c.fAll) threshold = t;
  else break;
}

const pct = (a: number, b: number) => `${((100 * a) / Math.max(b, 1)).toFixed(1)}%`;
const line = (name: string, set: Scored[], skip: (s: Scored) => boolean, score: (s: Scored) => number) => {
  const c = cost(set, skip);
  const a = auc(set.map((s) => ({ score: score(s), positive: s.y === 1 })));
  console.log(`  ${name.padEnd(9)} AUC ${a.toFixed(3)} | skip ${pct(c.skipped, c.n)} of ${c.n} | decisions lost ${c.dLost}/${c.dAll} (${pct(c.dLost, c.dAll)}) | facts lost ${c.fLost}/${c.fAll} (${pct(c.fLost, c.fAll)})`);
};

console.log(`train: ${train.length} sessions (${train.filter((s) => s.y).length} yielding); fitted threshold P(stored) < ${threshold.toFixed(3)}`);
for (const [label, set] of [
  ["yield holdout", scored.filter((s) => s.row.set === "yield" && splitOf(s.row.id) === "holdout")],
  ["live holdout", scored.filter((s) => s.row.set === "live" && splitOf(s.row.id) === "holdout")],
  ["audited (all)", scored.filter((s) => s.row.set === "audited")],
] as const) {
  console.log(`\n${label}:`);
  line("fitted", set, (s) => prob(s) < threshold, prob);
  line("baseline", set, (s) => s.imp < BASELINE, (s) => s.imp);
  if (label.startsWith("audited")) {
    const pos = set.filter((s) => worthwhile.get(s.row.id));
    const miss = pos.filter((s) => prob(s) < threshold).length;
    const [lo] = wilson(pos.length - miss, pos.length);
    console.log(`  fitted: audited-worthwhile skipped ${miss} of ${pos.length} (kept lower bound ${(100 * lo).toFixed(0)}%); baseline skipped ${pos.filter((s) => s.imp < BASELINE).length}`);
  }
}
console.log(`\nweights: ${GATE_FEATURES.map((f, i) => `${f} ${fit.weights[i]!.toFixed(2)}`).join(", ")}`);

if (process.argv.includes("--write")) {
  const model: GateModel = { ...fit, threshold };
  const r = (xs: readonly number[]) => `[${xs.map((v) => Number(v.toFixed(6))).join(", ")}]`;
  writeFileSync(join(import.meta.dirname, "../../src/core/classifier/gate-model-params.ts"),
    `// Generated by scripts/eval/clef-gate-fit.ts from ${train.length} tune sessions. Do not edit; refit instead.\n` +
    `import type { GateModel } from "./gate-model.js";\n\n` +
    `export const GATE_MODEL: GateModel = {\n  mean: ${r(model.mean)},\n  std: ${r(model.std)},\n  weights: ${r(model.weights)},\n` +
    `  bias: ${Number(model.bias.toFixed(6))},\n  threshold: ${Number(model.threshold.toFixed(6))},\n};\n`);
  console.log("wrote src/core/classifier/gate-model-params.ts");
}
