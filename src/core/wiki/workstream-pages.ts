/**
 * SPIKE (T1612, timeboxed): per-workstream wiki pages.
 *
 * One page per workstream with >= MIN_SESSIONS member sessions, built from
 * the member sessions' own labels/decisions/open loops plus the workstream's
 * accumulated facts. Pure functions, no IO, no new stores: the caller reads
 * via rollupWorkstream + session reads and writes pages to reports/ or tmp.
 *
 * Gated behind NLM_WIKI_WORKSTREAM (default off). If the ablation in
 * scripts/eval/wiki-spike-eval.ts does not justify the feature, delete this
 * file and its test instead of productizing it.
 */
import type { Workstream } from "@core/workstream/model.js";
import type { Fact, Session } from "@shared/types.js";
import { slugify } from "./slug.js";
import type { RenderedPage } from "./types.js";

export const WORKSTREAM_WIKI_FLAG = "NLM_WIKI_WORKSTREAM";
export const MIN_SESSIONS = 2;
/** Borges guard: total wiki bytes must stay under this fraction of source bytes. */
export const BORGES_LIMIT = 0.5;

export function isWorkstreamWikiEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  const raw = env[WORKSTREAM_WIKI_FLAG];
  return raw === "1" || (raw !== undefined && raw.toLowerCase() === "true");
}

export interface WorkstreamPageInput {
  readonly workstream: Workstream;
  readonly sessions: ReadonlyArray<Session>;
  readonly facts: ReadonlyArray<Fact>;
}

/** Source bytes the page distills: what the Borges guard measures against. */
export function workstreamSourceBytes(sessions: ReadonlyArray<Session>): number {
  return sessions
    .map((s) =>
      [s.label, s.summary, s.body, ...s.decisions, ...s.open, ...s.entities].join("\n"),
    )
    .join("\n").length;
}

export function checkBorgesGuard(
  wikiBytes: number,
  sourceBytes: number,
  limit: number = BORGES_LIMIT,
): { readonly ratio: number; readonly pass: boolean } {
  if (sourceBytes <= 0) return { ratio: Number.POSITIVE_INFINITY, pass: false };
  const ratio = wikiBytes / sourceBytes;
  return { ratio, pass: ratio < limit };
}

function dedupe(items: ReadonlyArray<string>): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of items) {
    const trimmed = item.trim();
    if (trimmed && !seen.has(trimmed)) {
      seen.add(trimmed);
      out.push(trimmed);
    }
  }
  return out;
}

/**
 * Build one markdown page for a workstream. Returns null when the workstream
 * has fewer than MIN_SESSIONS sessions or nothing worth saying (no
 * decisions, open loops, or facts): a page that adds nothing is index noise.
 * Session links are `session:<id>` code spans — relative on purpose, so a
 * synced page never carries a dead loopback link.
 */
export function buildWorkstreamPage(input: WorkstreamPageInput): RenderedPage | null {
  const { workstream, sessions, facts } = input;
  if (sessions.length < MIN_SESSIONS) return null;

  const current = facts.filter((f) => f.supersededBy === null);
  const decisions = dedupe([
    ...sessions.flatMap((s) => s.decisions),
    ...current.filter((f) => f.kind === "decision").map((f) => f.value),
  ]);
  const open = dedupe([
    ...sessions.flatMap((s) => s.open),
    ...current.filter((f) => f.kind === "open").map((f) => f.value),
  ]);
  const attrs = current.filter((f) => f.kind === "attribute");
  if (decisions.length === 0 && open.length === 0 && attrs.length === 0) return null;

  const ordered = sessions.slice().sort((a, b) => a.startedAt.localeCompare(b.startedAt));
  const slug = `ws-${slugify(workstream.label)}`;
  const lines: string[] = [
    "---",
    `title: ${JSON.stringify(workstream.label)}`,
    "nlm_generated: true",
    "spike: T1612",
    `session_count: ${ordered.length}`,
    `fact_count: ${current.length}`,
    "---",
    "",
    `> Spike page for workstream ${JSON.stringify(workstream.label)} (${ordered.length} sessions).`,
    "> Generated by NLM. Edits are overwritten.",
    "",
  ];
  if (decisions.length > 0) {
    lines.push("## Decisions", "");
    for (const d of decisions) lines.push(`- ${d}`);
    lines.push("");
  }
  if (open.length > 0) {
    lines.push("## Open loops", "");
    for (const o of open) lines.push(`- ${o}`);
    lines.push("");
  }
  if (attrs.length > 0) {
    lines.push("## Key facts", "");
    for (const f of attrs.slice().sort((a, b) => a.id.localeCompare(b.id))) {
      lines.push(`- ${f.subject} ${f.predicate} ${f.value}  ^${f.id}`);
    }
    lines.push("");
  }
  lines.push("## Sessions", "");
  for (const s of ordered) {
    const label = s.label.trim() || s.id;
    lines.push(`- ${label} \`session:${s.id}\``);
  }
  lines.push("");
  return { relPath: `${slug}.md`, content: lines.join("\n") };
}

export function buildWorkstreamIndex(
  pages: ReadonlyArray<{ readonly workstream: Workstream; readonly page: RenderedPage }>,
  today: string,
): RenderedPage {
  const sorted = pages.slice().sort((a, b) => a.workstream.label.localeCompare(b.workstream.label));
  const lines: string[] = [
    "---",
    "title: Workstream index",
    "nlm_generated: true",
    "spike: T1612",
    `last_projected: ${today}`,
    "---",
    "",
    `> Spike index. ${sorted.length} workstream page${sorted.length === 1 ? "" : "s"}.`,
    "",
  ];
  for (const { workstream, page } of sorted) {
    lines.push(`- ${workstream.label} ([[${page.relPath.replace(/\.md$/, "")}]])`);
  }
  lines.push("");
  return { relPath: "ws-index.md", content: lines.join("\n") };
}
